import fs from 'node:fs/promises';
import {stripTypeScriptTypes} from 'node:module';
const root=new URL('../google/',import.meta.url);
const rules=stripTypeScriptTypes(await fs.readFile(new URL('Rules.ts',root),'utf8')).replace(/[ \t]+$/gm,'');
const gateway=await fs.readFile(new URL('Gateway.js',root),'utf8');
await fs.writeFile(new URL('BookingGateway.gs',root),'// Generated by npm run build:gateway. Deploy this one file.\n'+rules+'\n'+gateway);
console.log('Built google/BookingGateway.gs');
